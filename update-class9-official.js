function normalize(s) {
  return (s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
}

function toTitleCase(n) {
  if (!n) return '';
  return n.trim().toLowerCase().split(/\s+/).map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

function formatDob(d) {
  if (!d) return '';
  return d.trim().replace(/\//g, '-');
}

async function updateClass9() {
  await mongoose.connect(process.env.MONGODB_URI, { dbName: process.env.DB_NAME || 'school_erp' });
  const dbStudents = await Student.find({ classId: 'class-9' }).sort({ rollNumber: 1, roll: 1 });

  const inputRows = rawInput.trim().split('\n').map(line => {
    const parts = line.split('\t').map(p => p.trim());
    return {
      name: parts[0],
      dob: parts[1],
      phone: parts[2],
      mother: parts[3],
      father: parts[4],
      penNumber: parts[5],
      apaarId: parts[6]
    };
  });

  const matched = [];
  const matchedDbIds = new Set();
  const unmatchedInput = [];

  for (const input of inputRows) {
    const inNameNorm = normalize(input.name);
    const inPen = input.penNumber;
    const inFatherNorm = normalize(input.father);
    const inMotherNorm = normalize(input.mother);

    let candidate = null;

    // 1. Match by PEN if valid and unique
    if (inPen && inPen.length >= 8) {
      candidate = dbStudents.find(s => s.penNumber === inPen && !matchedDbIds.has(s._id.toString()));
    }

    // 2. Match by exact normalized student name + father or mother or phone
    if (!candidate) {
      candidate = dbStudents.find(s => {
        if (matchedDbIds.has(s._id.toString())) return false;
        if (normalize(s.name) !== inNameNorm) return false;
        if (inFatherNorm && normalize(s.father).includes(inFatherNorm.slice(0, 4))) return true;
        if (inMotherNorm && normalize(s.mother).includes(inMotherNorm.slice(0, 4))) return true;
        if (input.phone && s.phone === input.phone) return true;
        return true;
      });
    }

    // 3. Match by name variations
    if (!candidate) {
      candidate = dbStudents.find(s => {
        if (matchedDbIds.has(s._id.toString())) return false;
        const dbNameNorm = normalize(s.name);
        const norm1 = inNameNorm.replace(/kh/g, 'k').replace(/sh/g, 's').replace(/ee/g, 'i').replace(/oo/g, 'u').replace(/tt/g, 't').replace(/oj/g, 'aj');
        const norm2 = dbNameNorm.replace(/kh/g, 'k').replace(/sh/g, 's').replace(/ee/g, 'i').replace(/oo/g, 'u').replace(/tt/g, 't').replace(/oj/g, 'aj');
        if (norm1 === norm2) return true;
        if (inNameNorm === 'bijayadas' && (dbNameNorm === 'bijoyadas' || dbNameNorm === 'bijayadas')) return true;
        return false;
      });
    }

    // 4. Match by Father + Mother + Phone
    if (!candidate) {
      candidate = dbStudents.find(s => {
        if (matchedDbIds.has(s._id.toString())) return false;
        const sFather = normalize(s.father);
        const sMother = normalize(s.mother);
        if (inFatherNorm && sFather && (sFather.includes(inFatherNorm) || inFatherNorm.includes(sFather))) {
          if (inMotherNorm && sMother && (sMother.includes(inMotherNorm) || inMotherNorm.includes(sMother))) {
            return true;
          }
        }
        return false;
      });
    }

    if (candidate) {
      matchedDbIds.add(candidate._id.toString());
      matched.push({ input, db: candidate });
    } else {
      unmatchedInput.push(input);
    }
  }

  console.log(`Matched: ${matched.length} students to update.`);

  let updatedCount = 0;
  for (const { input, db } of matched) {
    const student = await Student.findById(db._id);
    if (!student) continue;

    let changed = false;

    // 1. Correct student name spelling
    const properName = toTitleCase(input.name);
    if (properName && student.name !== properName) {
      // Check if misspelled in DB
      if (normalize(student.name) !== normalize(properName) || student.name.toLowerCase() !== properName.toLowerCase()) {
        console.log(`[Roll #${student.roll}] Updating name: "${student.name}" -> "${properName}"`);
        student.name = properName;
        changed = true;
      }
    }

    // 2. Correct Father's name
    const properFather = toTitleCase(input.father);
    if (properFather && student.father !== properFather) {
      student.father = properFather;
      student.guardian = properFather;
      changed = true;
    }

    // 3. Correct Mother's name
    const properMother = toTitleCase(input.mother);
    if (properMother && student.mother !== properMother) {
      student.mother = properMother;
      changed = true;
    }

    // 4. Update PEN number if empty or different
    if (input.penNumber && student.penNumber !== input.penNumber) {
      student.penNumber = input.penNumber;
      changed = true;
    }

    // 5. Update APAAR ID
    const properApaar = input.apaarId === 'Not Available' ? 'Not Available' : input.apaarId;
    if (properApaar && student.apaarId !== properApaar) {
      student.apaarId = properApaar;
      changed = true;
    }

    // 6. Update DOB
    const formattedDob = formatDob(input.dob);
    if (formattedDob && (!student.dob || student.dob !== formattedDob)) {
      student.dob = formattedDob;
      changed = true;
    }

    // 7. Update Phone
    if (input.phone && (!student.phone || student.phone !== input.phone)) {
      student.phone = input.phone;
      changed = true;
    }

    if (changed) {
      await student.save();
      updatedCount++;
    }
  }

  console.log(`\nSuccessfully verified and updated ${updatedCount} Class 9 students in MongoDB.`);
  console.log('Roll numbers were strictly maintained as-is.');

  await mongoose.disconnect();
}

updateClass9();
