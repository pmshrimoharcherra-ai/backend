async function updateClass7Details() {
  try {
    console.log('Connecting to MongoDB Atlas...');
    await mongoose.connect(MONGO_URI, { dbName: DB_NAME });
    console.log(`Connected to database: ${mongoose.connection.name}`);

    const existingStudents = await Student.find({ classId: 'class-7' }).sort({ rollNumber: 1 });
    console.log(`Found ${existingStudents.length} students in Class VII in database.`);

    let updatedCount = 0;

    for (const update of class7Data) {
      const student = existingStudents.find((s) => (s.rollNumber || parseInt(s.roll, 10)) === update.roll);

      if (student) {
        student.name = update.name;
        student.caste = update.caste;
        student.father = update.father;
        student.mother = update.mother;
        student.guardian = update.guardian || update.father || update.mother || student.guardian;
        if (update.dob) student.dob = update.dob;
        student.admissionDate = update.admissionDate;
        student.admissionNo = update.admissionNo;
        student.address = update.address;
        student.aadhaar = update.aadhaar;
        student.phone = update.phone;
        if (update.gender) student.gender = update.gender;
        if (update.status) student.status = update.status;

        await student.save();
        updatedCount++;
        console.log(`[UPDATED] Roll ${update.roll.toString().padStart(2, '0')}: ${update.name.padEnd(22, ' ')} | Caste: ${(update.caste || '-').padEnd(4, ' ')} | Adm Date: ${(update.admissionDate || '-').padEnd(10, ' ')} | Adm No: ${(update.admissionNo || '-').padEnd(3, ' ')} | Status: ${update.status} | Phone: ${(update.phone || '-').padEnd(10, ' ')} | Aadhaar: ${update.aadhaar || 'Pending'}`);
      } else {
        console.warn(`[NOT FOUND] Roll ${update.roll} not found in database.`);
      }
    }

    console.log(`\n================ Summary ================`);
    console.log(`Total Class VII students updated: ${updatedCount} of ${class7Data.length}.`);

    await mongoose.disconnect();
    console.log('Database disconnected cleanly.');
    process.exit(0);
  } catch (err) {
    console.error('Error updating Class VII details:', err);
    process.exit(1);
  }
}

